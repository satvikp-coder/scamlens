/**
 * Evaluation harness. It does not fail on mistakes in the held-out set: its
 * job is to MEASURE and REPORT. With WRITE_EVAL_REPORT=1 (see `npm run
 * evaluate`) it writes docs/EVALUATION.md from the real results.
 */

import * as fs from 'fs';
import * as path from 'path';
import { analyzeMessage, analyzeUrl } from './index';
import { DATASET, LABEL_LEVELS, type Fixture, type Lang, type Split } from './__fixtures__/dataset';

interface Row {
  fixture: Fixture;
  level: string;
  ok: boolean;
}

function evaluate(fixtures: Fixture[]): Row[] {
  return fixtures.map((fixture) => {
    const r = fixture.kind === 'message' ? analyzeMessage(fixture.text) : analyzeUrl(fixture.text);
    const allowed = fixture.expect ?? LABEL_LEVELS[fixture.label];
    return { fixture, level: r.level, ok: allowed.includes(r.level) };
  });
}

function summarize(rows: Row[]) {
  const susp = rows.filter((r) => r.fixture.label === 'suspicious');
  const benign = rows.filter((r) => r.fixture.label === 'benign');
  const flaggedAsSusp = (r: Row) => r.level === 'caution' || r.level === 'high';
  const tp = susp.filter(flaggedAsSusp).length;
  const fn = susp.length - tp;
  const fp = benign.filter(flaggedAsSusp).length;
  const tn = benign.length - fp;
  return {
    total: rows.length,
    suspicious: susp.length,
    benign: benign.length,
    other: rows.length - susp.length - benign.length,
    flagged: rows.filter(flaggedAsSusp).length,
    low: rows.filter((r) => r.level === 'low').length,
    unable: rows.filter((r) => r.level === 'unable').length,
    correct: rows.filter((r) => r.ok).length,
    tp,
    fn,
    fp,
    tn,
  };
}

const SPLITS: Split[] = ['dev', 'regression', 'heldout'];
const LANGS: Lang[] = ['en', 'hi', 'gu', 'hinglish', 'mixed'];

describe('evaluation report', () => {
  const rows = evaluate(DATASET);

  it('regression and dev sets have no mistakes', () => {
    const bad = rows.filter((r) => r.fixture.split !== 'heldout' && !r.ok);
    expect(bad.map((b) => b.fixture.id)).toEqual([]);
  });

  it('prints a summary and optionally writes docs/EVALUATION.md', () => {
    const lines: string[] = [];
    lines.push('# ScamLens evaluation report');
    lines.push('');
    lines.push('_Generated by `npm run evaluate` from the real engine. Do not edit by hand._');
    lines.push('');
    lines.push(
      'All examples are fictional and hand-written by the developers of the rules (with an AI assistant). ' +
        'This is a small SYNTHETIC test set. It checks that the rules behave as designed. ' +
        'It does NOT measure how well ScamLens would do on real scam messages, and the numbers below must not be quoted as the accuracy of the app.',
    );
    lines.push('');
    lines.push('## Results by split');
    lines.push('');
    lines.push('| Split | Examples | Flagged (caution/high) | Low | Unable | Matches expected label | Scam examples missed (FN) | Benign examples flagged (FP) |');
    lines.push('|---|---|---|---|---|---|---|---|');
    for (const split of [...SPLITS, 'all' as const]) {
      const subset = split === 'all' ? rows : rows.filter((r) => r.fixture.split === split);
      const s = summarize(subset);
      lines.push(`| ${split} | ${s.total} | ${s.flagged} | ${s.low} | ${s.unable} | ${s.correct} / ${s.total} | ${s.fn} of ${s.suspicious} | ${s.fp} of ${s.benign} |`);
    }
    lines.push('');
    const all = summarize(rows);
    const held = summarize(rows.filter((r) => r.fixture.split === 'heldout'));
    lines.push('## Precision and recall');
    lines.push('');
    lines.push(
      `Over all ${all.suspicious} scam and ${all.benign} benign examples: TP=${all.tp}, FN=${all.fn}, FP=${all.fp}, TN=${all.tn}. ` +
        `Precision = ${all.tp + all.fp === 0 ? 'n/a' : (all.tp / (all.tp + all.fp)).toFixed(2)}, ` +
        `recall = ${all.suspicious === 0 ? 'n/a' : (all.tp / all.suspicious).toFixed(2)}. ` +
        'These are inflated because the dev and regression examples were used to write and fix the rules.',
    );
    lines.push('');
    lines.push(
      `Held-out only (${held.suspicious} scam, ${held.benign} benign): TP=${held.tp}, FN=${held.fn}, FP=${held.fp}, TN=${held.tn}. ` +
        'With so few examples a single mistake changes the percentages a lot, so no precision/recall figure is quoted for this set.',
    );
    lines.push('');
    lines.push('## By language style (all splits)');
    lines.push('');
    lines.push('| Language style | Examples | Matches expected label |');
    lines.push('|---|---|---|');
    for (const lang of LANGS) {
      const subset = rows.filter((r) => r.fixture.lang === lang);
      lines.push(`| ${lang} | ${subset.length} | ${subset.filter((r) => r.ok).length} / ${subset.length} |`);
    }
    lines.push('');
    lines.push('Hindi, Gujarati and mixed-language sets are much smaller than English. Equal accuracy across languages is NOT claimed.');
    lines.push('');
    const misses = rows.filter((r) => !r.ok);
    lines.push('## Examples where the engine did not match the expected label');
    lines.push('');
    if (misses.length === 0) {
      lines.push('None.');
    } else {
      lines.push('| Id | Split | Expected | Engine said |');
      lines.push('|---|---|---|---|');
      for (const m of misses) {
        const expected = (m.fixture.expect ?? LABEL_LEVELS[m.fixture.label]).join(' or ');
        lines.push(`| ${m.fixture.id} | ${m.fixture.split} | ${expected} | ${m.level} |`);
      }
    }
    lines.push('');
    lines.push('## Known limitations of this evaluation');
    lines.push('');
    lines.push('- Synthetic, hand-written examples; real messages are messier and more varied.');
    lines.push('- Written by the same people who wrote the rules, so the examples reflect their assumptions.');
    lines.push('- Held-out set is tiny; it was written before the first run and not used for tuning, but it is still too small for reliable statistics.');
    lines.push('- No example set was reviewed by native Hindi or Gujarati speakers or by fraud investigators.');
    lines.push('- No test of adversarial scammers who adapt their wording to avoid the rules.');
    lines.push('');
    const report = lines.join('\n');
    console.log(report);
    if (process.env.WRITE_EVAL_REPORT === '1') {
      const out = path.join(__dirname, '..', '..', 'docs', 'EVALUATION.md');
      fs.mkdirSync(path.dirname(out), { recursive: true });
      fs.writeFileSync(out, report + '\n', 'utf8');
    }
    expect(report.length).toBeGreaterThan(100);
  });
});
